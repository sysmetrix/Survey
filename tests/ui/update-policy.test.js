// ───────────── 버전 ─────────────
test("parseVersion: 숫자·점만, 2~4 마디", () => {
  assert.deepEqual(parseVersion("5.28.0"), [5, 28, 0]);
  assert.deepEqual(parseVersion(" 5.28 "), [5, 28]);
  for (const bad of ["", "5", "v5.28.0", "5.28.0-beta", "5..0", "a.b.c", "1.2.3.4.5", null, undefined, 5.28, "5.28.0\n; drop"]) assert.equal(parseVersion(bad), null, String(bad));
});

test("compareVersions: 크기 순서·마디 수 차이·해석 불가", () => {
  assert.equal(compareVersions("5.28.0", "5.28.0"), 0);
  assert.equal(compareVersions("5.29.0", "5.28.9"), 1);
  assert.equal(compareVersions("5.9.0", "5.28.0"), -1, "문자열이 아니라 숫자 비교");
  assert.equal(compareVersions("6.0.0", "5.99.99"), 1);
  assert.equal(compareVersions("5.28", "5.28.0"), 0);
  assert.equal(compareVersions("5.28.1", "5.28"), 1);
  assert.equal(compareVersions("x", "5.28.0"), null);
  assert.equal(compareVersions("5.28.0", undefined), null);
});

// ───────────── sw.js 원문 파싱 ─────────────
const SW = `// 서비스워커\n// <generated by tools/build-sw.mjs>\nconst VERSION = "5.29.1";\nconst REVISION = "ABCDEF0123456789";\nconst ASSETS = [];\n// </generated>\nconst SHELL = \`x\`;`;

test("parseSwVersion: 정상 sw.js 에서 버전·리비전(소문자화)", () => {
  assert.deepEqual(parseSwVersion(SW), { version: "5.29.1", revision: "abcdef0123456789" });
  assert.deepEqual(parseSwVersion(SW.replace(/\n/g, "\r\n")), { version: "5.29.1", revision: "abcdef0123456789" }, "CRLF 도 허용");
});

test("parseSwVersion: 리비전이 없거나 이상해도 버전만 있으면 통과", () => {
  assert.deepEqual(parseSwVersion('const VERSION = "5.30.0";'), { version: "5.30.0", revision: null });
  assert.deepEqual(parseSwVersion('const VERSION = "5.30.0";\nconst REVISION = "xyz!";'), { version: "5.30.0", revision: null });
});

test("parseSwVersion: 깨진 원문·오류 페이지·빈 응답·형식 변경은 null", () => {
  for (const bad of ["", null, undefined, 42, "<!doctype html><title>404</title>", "const REVISION = \"abcdef0123\";", 'const VERSION = "";', 'const VERSION = "latest";', "const VERSION = '5.28.0';", 'var VERSION = "5.28.0"', "// const VERSION = \"5.28.0\"", 'const VERSION = "5.28.0'])
    assert.equal(parseSwVersion(bad), null, String(bad).slice(0, 40));
});

test("parseSwVersion: 매우 큰 응답도 앞부분만 보고 빠르게 처리", () => {
  const big = `${SW}\n${"x".repeat(5_000_000)}`;
  assert.equal(parseSwVersion(big).version, "5.29.1");
  assert.equal(parseSwVersion(`${"y".repeat(30_000)}\nconst VERSION = "5.29.1";`), null, "앞 20KB 밖은 무시");
});

test("releaseKey: 버전+리비전, 정보 없으면 빈 문자열", () => {
  assert.equal(releaseKey({ version: "5.29.0", revision: "ab12cd" }), "5.29.0#ab12cd");
  assert.equal(releaseKey({ version: "5.29.0", revision: null }), "5.29.0#");
  assert.equal(releaseKey(null), "");
  assert.equal(releaseKey({}), "");
});

// ───────────── 업데이트 감지 ─────────────
test("detectUpdate: 더 높은 버전은 업데이트", () => {
  const d = detectUpdate({ version: "5.28.0", revision: "aaaaaa" }, { version: "5.29.0", revision: "bbbbbb" });
  assert.deepEqual(d, { available: true, reason: "newer", version: "5.29.0" });
});

test("detectUpdate: 같은 버전·같은 리비전은 업데이트 아님", () => {
  assert.equal(detectUpdate({ version: "5.28.0", revision: "aaaaaa" }, { version: "5.28.0", revision: "aaaaaa" }).available, false);
  assert.equal(detectUpdate({ version: "5.28.0", revision: "aaaaaa" }, { version: "5.28.0", revision: "aaaaaa" }).reason, "same");
});

test("detectUpdate: 같은 버전이라도 리비전이 다르면(버전을 올리지 않은 배포) 업데이트", () => {
  const d = detectUpdate({ version: "5.28.0", revision: "aaaaaa" }, { version: "5.28.0", revision: "bbbbbb" });
  assert.equal(d.available, true);
  assert.equal(d.reason, "revision");
});

test("detectUpdate: 실행 중 리비전을 모르면(예전 서비스워커·첫 방문) 같은 버전은 업데이트 아님", () => {
  assert.equal(detectUpdate({ version: "5.28.0", revision: null }, { version: "5.28.0", revision: "bbbbbb" }).available, false);
  assert.equal(detectUpdate({ version: "5.28.0" }, { version: "5.28.0", revision: null }).available, false);
});

test("detectUpdate: 서버가 더 낮은 버전(오래된 CDN 사본·롤백)은 여기서 업데이트로 보지 않음", () => {
  const d = detectUpdate({ version: "5.28.0", revision: "aaaaaa" }, { version: "5.27.0", revision: "cccccc" });
  assert.deepEqual(d, { available: false, reason: "older", version: "5.27.0" });
});

test("detectUpdate: 원격 정보 없음·형식 오류는 조용히 '알 수 없음'", () => {
  for (const remote of [null, undefined, {}, { version: "" }, { version: "abc" }, { version: null, revision: "aa" }])
    assert.equal(detectUpdate({ version: "5.28.0", revision: "aaaaaa" }, remote).available, false);
  assert.equal(detectUpdate({ version: "??" }, { version: "5.28.0" }).available, false, "실행 버전이 이상해도 오탐하지 않음");
});

test("detectUpdate: 파싱한 sw.js 와 곧바로 연결", () => {
  const remote = parseSwVersion(SW);
  assert.equal(detectUpdate({ version: "5.28.0", revision: "0000000000000000" }, remote).available, true);
  assert.equal(detectUpdate({ version: "5.29.1", revision: "abcdef0123456789" }, remote).available, false);
});

