  assert.equal(parseResume(raw, T0 + 2 * 60_000 + 1), null, "2분 지나면 무효");
  assert.equal(parseResume(raw, T0 - 60_000), null, "미래 시각은 무효");
  assert.deepEqual(parseResume(JSON.stringify({ projectId: "p-1", hash: "javascript:x", at: T0 }), T0), { projectId: "p-1", hash: "", at: T0 }, "# 로 시작하지 않는 hash 는 버림");
  for (const bad of [null, "", "{", "[]", "{}", '{"projectId":"","at":1}', '{"projectId":5,"at":1}', `{"projectId":"p","at":"x"}`]) assert.equal(parseResume(bad, T0), null, String(bad));
