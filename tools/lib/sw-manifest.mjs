import { readFile, readdir } from "node:fs/promises";
import { createHash } from "node:crypto";

async function walk(dir, filter) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = `${dir}/${e.name}`;
    if (e.isDirectory()) out.push(...await walk(p, filter));
    else if (filter(p)) out.push(p);
  }
  return out;
}

/** 앱 셸: 화면·스타일·모듈·라이브러리·아이콘·샘플 (글꼴 조각은 사용 시 캐시) */
export async function collectAssets() {
  const list = [
    "index.html", "manifest.webmanifest",
    "vendor/papaparse-5.4.1.min.js", "vendor/xlsx-0.20.3.full.min.js", "vendor/jszip-3.10.1.min.js",
    "vendor/fonts/pretendard-gov/pretendard-gov-dynamic-subset.css",
    ...await walk("css", p => p.endsWith(".css")),
    ...await walk("js", p => p.endsWith(".js")),
    ...await walk("icons", p => /\.(png|svg)$/.test(p)),
    ...await walk("samples", p => /\.(xlsx|csv)$/.test(p)),
  ];
  return [...new Set(list)].sort();
}

export async function computeRevision(assets) {
  const h = createHash("sha256");
  for (const a of assets) {
    let buf = await readFile(a);
    // Git 자동 줄바꿈 변환(CRLF/LF)과 무관하게 같은 값이 나오도록 텍스트는 LF 로 통일
    if (!/\.png$/.test(a)) buf = Buffer.from(buf.toString("utf8").replace(/\r\n/g, "\n"));
    h.update(a); h.update("\0"); h.update(buf); h.update("\0");
  }
  return h.digest("hex").slice(0, 16);
}

export async function appVersion() {
  const m = /APP_VERSION = "([^"]+)"/.exec(await readFile("js/main.js", "utf8"));
  if (!m) throw new Error("js/main.js 에서 APP_VERSION 을 찾지 못함");
  return m[1];
}

const START = "// <generated by tools/build-sw.mjs>", END = "// </generated>";
/** sw.js 원문에 생성 블록을 채운 결과 (줄바꿈은 \n 기준) */
export async function buildSwSource(src) {
  const assets = await collectAssets();
  const block = `${START}\nconst VERSION = ${JSON.stringify(await appVersion())};\nconst REVISION = ${JSON.stringify(await computeRevision(assets))};\nconst ASSETS = ${JSON.stringify(assets.map(a => encodeURI(a)), null, 2)};\n${END}`;
  const i = src.indexOf(START), j = src.indexOf(END);
  if (i < 0 || j < 0) throw new Error("sw.js 생성 블록 표시를 찾지 못함");
  return src.slice(0, i) + block + src.slice(j + END.length);
}
